export const generate200Monitors = () => {
  return REAL_SITES_CATALOG.map((site, index) => {
    const idNum = index + 1;
    const id = `real-mon-${String(idNum).padStart(3, '0')}`;

    // Realistic real-world status
    // Site #200 (httpbin 404) is purposely marked 'down' to demonstrate incident tracking!
    const isSpecial404 = site.url.includes('/status/404');
    const isPaused = idNum === 19 || idNum === 48; // a couple paused for UI variety

    let status = 'up';
    let statusCode = 200;
    let errorMessage = null;

    if (isSpecial404) {
      status = 'down';
      statusCode = 404;
      errorMessage = 'HTTP 404: Not Found (Target test failure)';
    } else if (isPaused) {
      status = 'paused';
    }

    // Typical real-world latencies:
    // CDNs/Search (25-80ms), Complex Portals (120-220ms), APIs (90-300ms)
    let baseLatency = 45;
    if (site.category === 'Search & Portals') baseLatency = 35 + (idNum % 25);
    else if (site.category === 'Cloud Infrastructure') baseLatency = 28 + (idNum % 30);
    else if (site.category === 'Live Public APIs') baseLatency = 95 + (idNum % 85);
    else baseLatency = 65 + (idNum % 60);

    if (isSpecial404) baseLatency = 140;

    // Realistic sparkline array
    const history = Array.from({ length: 12 }, (_, hIdx) => {
      const variation = Math.floor(Math.sin((idNum + hIdx) * 0.9) * 12);
      return Math.max(15, baseLatency + variation);
    });

    const uptime7d = isSpecial404 ? 92.45 : Math.round((99.75 + (idNum % 24) * 0.01) * 100) / 100;
    const uptime30d = isSpecial404 ? 94.10 : Math.round((99.82 + (idNum % 17) * 0.01) * 100) / 100;
    const minutesAgo = idNum % 30;

    return {
      _id: id,
      id: id,
      name: site.name,
      url: site.url,
      method: 'GET',
      interval: idNum % 5 === 0 ? 1 : 5,
      timeout: 10000,
      status,
      isActive: !isPaused,
      statusCode,
      lastResponseTime: baseLatency,
      uptime7d,
      uptime30d,
      lastChecked: new Date(Date.now() - minutesAgo * 60 * 1000).toISOString(),
      errorMessage,
      category: site.category,
      history,
      createdAt: new Date(Date.now() - idNum * 3600 * 1000).toISOString()
    };
  });
};

